export const NO_AI_VOICE = `
=== 文字层禁令（凡是你写出来的中文，都要过这一关）===

下面这些是 AI 写作的典型痕迹。命中即改，不要出现在任何字段里。

**禁用词（命中即清零）**
不由得、霎时间、殊不知、良久、顿时、瞬间、恍然大悟、微微一笑、嘴角微微上扬、
轻轻叹了口气、眼底闪过一丝波澜、眼底划过一丝、喉结滚动、周身气场、心中五味杂陈、
气氛瞬间凝滞、声音很平、心中暗道、此刻心中暗想、就在这时、紧接着、仿佛

**堆叠副词**（同一段内重复即删到只剩一处）
极其、极度、猛地、死死、狠狠、稳稳

**禁用句式**
- 二分对照壳：「不是 A 而是 B」「不仅……而且……」「这不仅仅是……而是……」
- 破折号；提示语冒号（「概念：解释」「原因：结论」这种模板）
- 三段式凑数：只因为三是个整数就凑三样东西

**禁用比喻**
如沐春风、梨花带雨、像一位智慧的导师、像永不疲倦的秘书，以及任何"无害、安全、通用"的喻体。
比喻宁可没有，也不要安全牌。

**两条节奏约束**
- 不要段尾补抽象结论。停在具体事实、具体后果、具体动作上。
- 不要每句一样长。要有极短句，也要有长句。
`.trim();

