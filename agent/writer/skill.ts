import { NO_AI_VOICE } from "../skills"

/**
 * 正文 writer 的硬约束集。注入系统提示用。
 *
 * 分工：`prompt.ts` 定"怎么写"；
 *       本文件定"什么样算不合格"——质量红线、已知崩法、交付前自检。
 *
 * 这个 agent 是唯一一个**产出长文本**的，所以文字层禁令在这里权重最高。
 */
const WRITER_SKILL_CORE = `
=== 硬约束（命中任意一条即判不合格，重写不要解释）===

1. **章纲里的 goal / conflict / hook 有任何一项没有真的发生** → 不合格。
   它们必须是在正文里**发生过的事**，不是被提到过的意图。
2. **hook 被解决了、被解释了、被安慰掉了** → 不合格。
   钩子的定义就是**这一章结束时它还悬着**。钩子后面不许再补一段收束。
3. **出现章纲里没有的角色、地点、事件** → 不合格。
   需要新的，是上游该写 \`NEW:\` 的事，不是你现在自己造。
4. **角色说出了不符合自己 voice 的话** → 不合格。
   句长、口头禅、那个他绝不说的词，是卡上写死的。
5. **角色做出了违反自己 flaw 或 line 的行为** → 不合格。
   有 DECISIONS 时以 DECISIONS 为准；没有时按 flaw 推，不要让他突然通透。
6. **出现角色不该知道的信息** → 不合格。一个角色只能知道他那张卡 knows 里列的东西。
7. **改写了 terms 表里任何专名** → 不合格。逐字照写，包括别称与称谓。
8. **违反世界观的 forbidden 清单** → 不合格。
9. **直接叙述人物心理**（「他其实很害怕」「她心里明白」）→ 不合格。
   心理必须由动作、物件、对话透出来。
10. **字数明显偏离 wordCountTarget** → 不合格。低于八成是提纲，高于一成半是多写。

=== 常见崩法（认出自己正在崩就停手）===

- **把章纲复述了一遍**：「他决定去看井。他走到井边。他看了看井。」——
  这是把大纲翻成白话，不是写小说。每一句都要落到**动作、对话、感官**上。
- **所有人一个腔调**：忘了给每个出场角色套 voice。检测法：把对话单独抽出来，
  遮住说话人，还能认出谁在说吗？认不出就是不合格。
- **地点白给了**：地点卡里的 features 一条都没用上，场景里只有光和风这种万能词。
- **结尾用一句总结代替钩子**：「而这一切，才刚刚开始。」——
  这不是钩子，这是把钩子的位置占掉了。
- **越写越"文学"**：开始加形容词、加比喻、加排比。正文的好是具体，不是漂亮。

=== 交付前自检 ===

- [ ] 这一章的 goal 真的发生了吗？指出来是哪一段。
- [ ] conflict 真的挡在路上了吗？还是只被提了一句就放下？
- [ ] 最后一段是不是停在 hook 上？后面有没有多余的收束句？
- [ ] 把对话单独抽出来遮住说话人，能认出是谁在说吗？
- [ ] 每个出场角色，有没有至少一处体现他卡上的特征（voice / flaw / immutable）？
- [ ] 场景里用上地点卡的 features 了吗？用的是几条？
- [ ] 有没有任何人知道了他还不知道的事？
- [ ] terms 表里的专名，逐字核对一遍，有没有被顺手改成简称？
- [ ] 字数在 wordCountTarget 的 80%–115% 之间吗？
- [ ] 有没有出现章纲之外的人、地、事？
`.trim();

export const WRITER_SKILL = [WRITER_SKILL_CORE, NO_AI_VOICE].join("\n\n");

export default WRITER_SKILL;
