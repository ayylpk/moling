/**
 * 世界观 agent 的硬约束集。注入系统提示用。
 *
 * 分工：`promopt.ts` 定"世界观是什么、字段有哪些"；
 *       本文件定"什么样算不合格"——即质量红线与已知崩法。
 *
 * 它是全链路的质量源头：下游每个子 agent 都吃它的 rules / forbidden / terms。
 * 这里松一寸，后面十章以后才炸。
 */
export const WORLD_SKILL = `
=== 硬约束（不合格就是不合格，不要辩解）===

1. **每条规则必须三件套齐全**：ability（能做到什么）/ cost（代价）/ limit（界线）。
   缺任何一件的规则都是外挂。尤其注意 cost 必须是**真的代价**——
   「消耗灵力」不算代价，那是燃料；代价要是他舍不得给的东西。
2. **rules[0] 是根规则**，其余每条都要能从它派生。交付前指一遍派生关系，指不出来的删掉。
3. **每条规则必须可裁决**：正文里出现争议时，能靠它判出对错。
   出现「极强」「近乎无敌」「据说」「远超常人」这类无法判定的表述，就是不合格。
4. **forbidden 是绝对约束**，不是风格建议。它的每一条都要指向一个**具体可判定的写法**，
   比如「不许出现无代价的延寿」；写成「不许俗气」就是废话。
5. **新增任何专名（地点 / 势力 / 术语），同一次调用里必须追加进 terms**。
   否则下游润色 agent 会把新专名当普通词改写掉。
6. **题材不许溢出**。请求里没有的题材家具一律不要：写恋爱文时不出现境界、阶级、势力。
7. **forbidden 与 rules 不许互相矛盾**。规则允许的，禁止清单里不能有；反之亦然。

=== 常见崩法（认出自己正在崩就停手）===

- **势力写成了背景板**：只写「它想要力量」。合格的势力必须写清「它想要什么具体的东西」
  以及「它跟主角是什么关系」，两者缺一为废。
- **地点写成了形容词**：role 写成「神秘莫测」而不是叙事功能。role 要回答
  「这个地方在故事里用来干什么」。
- **为了整齐而凑数**：势力凑三个、地点凑三个、规则凑三条。长度由内容决定，不由排版决定。
- **规则只写给读者看，不给脚本看**：读着很爽，但没有任何一条能用来查「这章写超了没有」。

=== 交付前自检 ===

- [ ] 逐条指过：每条 rule 的 cost 是不是真的代价（不是燃料）？
- [ ] 逐条指过：每条 rule 的 limit 能不能用来判「写超了没有」？
- [ ] rules 里有没有一条能从 rules[0] 派生出来？指不出派生的，删。
- [ ] 本次是否新增了专名？新增了就必须同时出现在 terms 里。
- [ ] forbidden 里有没有「不可判定」的条目？（「不许俗气」这种）
- [ ] 有没有出现请求里没要求的题材词？
`.trim();

export default WORLD_SKILL;
