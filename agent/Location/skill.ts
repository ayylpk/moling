import { NO_AI_VOICE } from "../skills"

/**
 * 地点卡 agent 的硬约束集。注入系统提示用。
 *
 * 分工：`prompt.ts` 定"字段是什么、怎么写"；
 *       本文件定"什么样算不合格"——质量红线、已知崩法、交付前自检。
 *
 * 这个 agent 最大的风险不是生成不出地点，是**生成出长得一样的十个地点**。
 * 所以自检里一半都在查"可辨识度"。
 */
const LOCATION_SKILL_CORE = `
=== 硬约束（命中任意一条即判不合格，重写不要解释）===

1. **parent 指向不存在的地方，或凭空造出新的洲 / 域 / 城** → 不合格。
   新地点只能挂在 WORLD 或 EXISTING 里已有的节点下。
2. **signature 与 EXISTING 里任何一个**结构同构** → 不合格。
   判定法：把两条 signature 的主语和宾语互换，如果都还成立，就是同一个点子。
3. **features 里出现纯形容词**（「灵气浓郁」「美如仙境」「气氛诡异」）→ 不合格。
   features 只放**五感能接到的东西**：什么颜色的光、什么声音、什么气味、脚下什么质地、什么天气。
4. **role 写成情绪或氛围**（「这里让人感到压抑」）→ 不合格。
   role 要回答「这个地方在故事里被用来干什么」：告白在哪、被跟梢在哪、秘密在哪曝光。
5. **引入世界观里不存在的题材家具** → 不合格。玄幻的秘境、都市的酒吧、校园的天台，
   取决于世界观实际是什么，不取决于你想写什么。
6. **一次输出多个地点** → 不合格。

=== 常见崩法（认出自己正在崩就停手）===

- **撞母题（比重名难防得多）**：有了「万年冰湖」，接着给「千年寒潭」，再来「终年不化的不冻泉」。
  三个名字，一个地方。读者会看出来。**查的是点子，不是字符串。**
- **同物异名**：青州旧观 / 青州古观 / 城郊废观——其实是同一个地方。
  生成前先扫一遍 EXISTING，命中就在已有条目上追加别名，不要新建。
- **features 三条全是视觉**：光、颜色、形状。这等于只用了一只眼睛。换一条给声音，换一条给气味或触感。
- **features 是万能的**：去掉地点名字之后，这几条能套到任何一个地点上——那它们不是这个地点的特征。

=== 交付前自检 ===

- [ ] parent 在 WORLD 或 EXISTING 里真的存在吗？
- [ ] 遮住 name，只看 features，能认出是哪个地点吗？认不出 → features 不合格。
- [ ] 把 signature 和 EXISTING 里每一条对调主谓，还成立吗？成立 → 同构，重写。
- [ ] features 里有没有哪一条是纯形容词？（能画出来吗？画不出来就是形容词）
- [ ] features 五感覆盖了几种？只有视觉 → 补一种。
- [ ] role 回答的是「用来干什么」还是「感觉怎么样」？
- [ ] 有没有引入世界观里没有的东西？
`.trim();

export const LOCATION_SKILL = [LOCATION_SKILL_CORE, NO_AI_VOICE].join("\n\n");

export default LOCATION_SKILL;
