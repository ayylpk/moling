import { NO_AI_VOICE } from "../skills"

/**
 * 故事架构师（大纲）agent 的硬约束集。注入系统提示用。
 *
 * 分工：`prompt.ts` 定"每个字段是什么、怎么写"；
 *       本文件定"什么样算不合格"——质量红线、已知崩法、交付前自检。
 *
 * 它是链路里**唯一一次调用要吐 50 章**的 agent，超长输出最容易"后半段塌成空话"。
 * 所以自检里一半在查"后半程有没有还在推进"。
 */
const ARCHITECT_SKILL_CORE = `
=== 硬约束（命中任意一条即判不合格，重写不要解释）===

1. **一次输出超过一卷** → 不合格。一卷就是一卷，约 50 章，不要顺手把下一卷也写了。
2. **章节 index 不从 PREVIOUS 给出的起始章号开始，或中途跳号** → 不合格。
   编号是全篇连续的，第二卷从 51 起，不从 1 重开。
3. **改写全篇锚点**（direction / structure.type / mainPlot / subplots）→ 不合格。
   第一卷定稿之后，这几项只能**原样回填**。改了哪怕一个词，那也是缺陷，不是修改。
4. **某一章没有 conflict** → 不合格。「赶路」「日常」「铺垫」这类章节直接删掉，
   不要为了让章数凑够而保留。
5. **同一章的 goal / conflict / hook 读起来是同一件事** → 不合格。三者塌成一句话就全部重写。
6. **constraints.locations 出现未登记的地名** → 不合格。这一节只抄不造。
7. **chapters 的 characters / place 里出现 CAST 和 PREVIOUS 之外的名字** → 不合格。
   需要新角色新地点，写 \`NEW:戏剧功能\`，由中心 agent 去补建，**不要自己起名**。
8. **endingDirection 出现「开放结局」「留白」「由作者决定」** → 不合格。结局必须确定。
9. **tensionCurve 全程在 5–6 之间** → 不合格。曲线没有起伏等于没有升级。
   也不许锯齿乱跳：整体必须往上爬。
10. **在某一卷里硬塞满六种转折点** → 不合格。六种类型分散在全篇，
    一卷通常只有一到两个；这卷没有 midpoint 就不要写 midpoint。
11. **summary 只有一两句话，而 wordCountTarget ≥ 2000** → 不合格。
    summary 是写手扩写的唯一蓝本：**summary 里数得出的节拍数 × 450 字 ≈ 这章实际写得出的字数**。
    节拍撑不起目标，写手就只能交一份概要——提示词怎么催都没用，因为它被禁止新增事件。
    修法：把本章按顺序拆成 4–6 个节拍写进 summary，或者把目标字数降下来。

=== 常见崩法（认出自己正在崩就停手）===

- **后半程塌成空话**：第 10 章还很具体，第 40 章变成「主角继续成长，遭遇新的挑战」。
  这是 token 用尽前的典型症状。发现自己开始写套话，停手，回到具体事件。
- **相邻章节互换也成立**：把第 35 章的 goal 和第 36 章的 goal 调换，读起来没区别。
  这说明这两章没有区分度，合并或重写。
- **冲突形态单一**：每章的 conflict 都是「有人拦着他」。冲突应该有不同类型：
  外部阻拦、信息缺失、他自己的选择、代价太高、时间不够。
- **卷末什么都没解决**：把「没解决」当成了钩子。钩子是**新的问题被打开**，
  不是**旧的问题没关**。本卷主要驱动力必须在末章前转到明确的转折点。
- **summary 写成了主题句**：「这一章两人关系出现裂痕」——这是**评价**，不是**节拍**。
  写手拿着它只能写出一段感悟。每章 summary 要按顺序列出 4–6 个事件步，
  每一步一个短句：谁做了什么、发生了什么变化。

=== 交付前自检 ===

- [ ] 章数是否约等于 NEED 要求（默认 50）？index 起始号对不对？有没有跳号？
- [ ] 非第一卷：direction / structure.type / mainPlot / subplots 是不是**逐字**回填的？
- [ ] 把每章的 goal 单独抽出来排成一列读一遍——**能看出升级吗**？
- [ ] 有没有哪一章删掉之后，前后接得上、读起来没损失？有 → 那一章是废章。
- [ ] 每章是否都有 conflict？有没有「赶路」「日常」「铺垫」式的空章？
- [ ] 每一章的 goal / conflict / hook 三者是不是读起来三件不同的事？
- [ ] tensionCurve 逐章有值吗？最高点落在 climaxChapters 上吗？整体是往上爬的吗？
- [ ] 本卷末章的钩子是「打开了新问题」还是「什么都没解决」？
- [ ] constraints.locations 里有没有 CAST / WORLD 之外的地名？
- [ ] chapters 里的 characters / place，除 \`NEW:\` 前缀外，是否全部已登记？
- [ ] 抽三章数一数：summary 里的节拍数 × 450 ≈ wordCountTarget 吗？差得远就是节拍不足。
`.trim();

export const ARCHITECT_SKILL = [ARCHITECT_SKILL_CORE, NO_AI_VOICE].join("\n\n");

export default ARCHITECT_SKILL;
