import { NO_AI_VOICE } from "../skills"

/**
 * 角色卡 agent 的硬约束集。注入系统提示用。
 *
 * 分工：`prompt.ts` 定"每个字段是什么、怎么写"；
 *       本文件定"什么样算不合格"——质量红线、已知崩法、交付前自检。
 */
const CHARACTER_SKILL_CORE = `
=== 硬约束（命中任意一条即判不合格，重写不要解释）===

1. **immutable 里出现性格词**（善良、冷酷、孤傲、多疑、心软）→ 不合格。
   immutable 只放**另一个人能看见或核验**的事实：缺的指节、疤、口音、随身物件、出身。
2. **need 与 want 同义** → 不合格。判断方法：把 need 遮住，只看 want，能推出 arc.end 吗？
   能推出来，说明 need 根本没起作用。
3. **arc.end 出现「开放」「待定」「由作者决定」「留给读者」** → 不合格。结局必须是确定状态。
   这个角色会死就写死，会变成敌人就写变成敌人。
4. **reveal 写成「终将揭晓」「时机成熟时」「在某个转折点」** → 不合格。
   必须是**具体的触发条件**：谁、在什么场合、说了什么或做了什么。
5. **relations 里存的是名字而不是 id+态度** → 不合格。
6. **出现不可核验的形容** → 不合格：「内心善良但外表冷酷」「深不可测」「连他自己都不明白」
   「谜一样的人」。这类词的作用只有填充字数。
7. **角色无所不能** → 不合格。没有做不到的事的角色，就没有能写的场景。
8. **一次输出多个角色** → 不合格。本 agent 一次只建一个。
9. **违反世界观 forbidden 清单 / 改名已在 terms 登记的任何专名** → 不合格。

=== 常见崩法（认出自己正在崩就停手）===

- **voice 写成了形容词**：「说话简短有力」「语气平静」。那不是行为，是评价。
  合格的 voice 要能被照着演：句子多长、有什么口头禅、**绝不说的那个词是什么**。
- **三个角色的 flaw 全撞一个方向**：都「不信任他人」、都「压抑情感」。这就是模板化。
  发现自己在重复上一张卡的缺陷结构，停手，换一个完全不同的方向。
- **want 和 need 用了同一个词根**：比如 want=「得到认可」、need=「被认可」。
  写的时候就该发现，这是同义不是区别。
- **immutable 与 flaw 抢戏**：把「他总是不敢看人眼睛」放进 immutable。
  那是行为习惯不是可核验事实，放 flaw 或 voice 里。

=== 交付前自检 ===

- [ ] 逐条念一遍 immutable：每一条另一个人都能**看见或核验**吗？
- [ ] 遮住 need，只看 want，能不能推出 arc.end？能 → need 失效，重写。
- [ ] arc.end 是确定状态吗？有没有一个词是「开放 / 待定 / 留白」？
- [ ] reveal 是具体触发条件吗？换成「某天，因为某件事」还成立的话，就是不合格。
- [ ] relations 里全是指针（id + 态度）吗？有没有混进名字？
- [ ] 这个角色有没有一件**他做不到**的事？没有 → 补上限制。
- [ ] 念一遍 voice：能照着演出一个具体的人吗？还是只是一句评价？
`.trim();

export const CHARACTER_SKILL = [CHARACTER_SKILL_CORE, NO_AI_VOICE].join("\n\n");

export default CHARACTER_SKILL;
